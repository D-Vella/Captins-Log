from sqlalchemy import (
    ForeignKey,
    String,
    Text,
    DateTime,
    Integer
)
from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    mapped_column,
    relationship
)
from datetime import datetime as dt
from typing import Optional

class Base(DeclarativeBase):
    """SQLAlchemy declarative base for all application models."""
    pass

class log_entry(Base):
    """Represents a daily log entry in the system.

    Attributes:
        id: Primary key.
        entry_date: Date of the log entry (string, format YYYY-MM-DD).
        created_at: Timestamp when the entry was first created.
        updated_at: Timestamp of the last update.
        log_segments: One-to-many relationship with audio segments for this entry.
    """
    __tablename__ = "log_entry"

    id: Mapped[int] = mapped_column(primary_key=True)
    entry_date: Mapped[str] = mapped_column(String(25))
    created_at: Mapped[dt] = mapped_column(DateTime)
    updated_at: Mapped[dt] = mapped_column(DateTime)
    
    log_segments: Mapped[list["log_segment"]] = relationship(back_populates="log_entry")

class log_segment(Base):
    """Represents an audio segment (recording + transcript) within a log entry.

    Attributes:
        id: Primary key.
        log_entry_id: Foreign key referencing the parent log entry.
        audio_filename: Name of the stored audio file.
        audio_duration: Duration of the audio in seconds.
        raw_transcript: The raw speech-to-text output.
        created_at: Timestamp when the segment was first created.
        updated_at: Timestamp of the last update.
        log_entry: Many-to-one relationship with the parent log entry.
    """
    __tablename__ = "log_segment"

    id: Mapped[int] = mapped_column(primary_key=True)
    log_entry_id: Mapped[int] = mapped_column(ForeignKey("log_entry.id"))
    audio_filename: Mapped[str] = mapped_column(String(255))
    audio_duration: Mapped[int] = mapped_column(Integer)
    raw_transcript: Mapped[str] = mapped_column(Text)
    created_at: Mapped[dt] = mapped_column(DateTime)
    updated_at: Mapped[dt] = mapped_column(DateTime)

    log_entry: Mapped["log_entry"] = relationship(back_populates="log_segments")

class log_enrichment(Base):
    """Holds LLM-generated enriched content for a log entry.

    Attributes:
        id: Primary key.
        log_entry_id: Foreign key referencing the parent log entry.
        formatted_md: The LLM-formatted Markdown version of the entry.
        followup_qs: Follow-up questions generated by the LLM for self-reflection.
        weekly_summary: Optional weekly summary generated by the LLM.
        created_at: Timestamp when the enrichment was first created.
        updated_at: Timestamp of the last update.
        log_entry: Many-to-one relationship with the parent log entry.
    """
    __tablename__ = "log_enrichment"

    id: Mapped[int] = mapped_column(primary_key=True)
    log_entry_id: Mapped[int] = mapped_column(ForeignKey("log_entry.id"))
    formatted_md: Mapped[str] = mapped_column(Text)
    followup_qs: Mapped[str] = mapped_column(Text)
    weekly_summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[dt] = mapped_column(DateTime)
    updated_at: Mapped[dt] = mapped_column(DateTime)

    log_entry: Mapped["log_entry"] = relationship(back_populates="log_enrichments")